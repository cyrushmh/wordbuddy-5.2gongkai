#!/usr/bin/env bash
# 按 Arch Package Guidelines 复刻 makepkg 流程，产出真实可安装的 .pkg.tar.zst。
#
# 为何自己复刻：本沙箱是 Ubuntu（无 makepkg/pacman）。脚本严格按 makepkg 的步骤与
# 元数据规范执行——build() → package_<name>() → 生成 .PKGINFO/.BUILDINFO/.MTREE →
# 打包 zstd —— 产出的包可被任何 Arch 系统的 `pacman -U` 安装。
# 在真 Arch 上直接 `makepkg -s` 即可，无需本脚本。
#
# 分包结构（范本：man-pages-zh_cn 的 .PKGINFO，xdata = pkgtype=split）：
#   classics        → 架构相关，按 x86_64 / aarch64 / riscv64 各打一份
#   classics-data   → arch=('any')，纯文本不随架构变化，只打一份
#
# 用法： bash build-arch.sh               # 构建
#        FILL_SUMS=1 bash build-arch.sh   # 构建并把真实 sha256 回填进 PKGBUILD
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$ROOT/arch-out"
PKGBASE=classics
PKGVER=1.0.0
PKGREL=1
BUILDDATE="$(date +%s)"
PACKAGER="windows-internals-toolkit <noreply@example.com>"

# 主包：架构 → 交叉编译器映射（原生 x86_64 用 cc）
declare -A CC_MAP=(
  [x86_64]="cc"
  [aarch64]="aarch64-linux-gnu-gcc"
  [riscv64]="riscv64-linux-gnu-gcc"
)

log() { echo ">>> $*"; }
die() { echo "!!! $*" >&2; exit 1; }

# ── .MTREE：makepkg 生成的文件清单（pacman 用它校验已装文件完整性）──────
# 格式取自真实包 man-pages-zh_cn：mtree 文本格式，每个文件带 mode/size/sha256digest。
gen_mtree() {
  local root="$1" out="$2" ts="$3"
  {
    echo "#mtree"
    echo "/set type=file uid=0 gid=0 mode=644"
    # 目录与文件按路径统一排序（与真实包一致：.BUILDINFO/.PKGINFO 排在 usr 之前），
    # 而非「先全部目录、再全部文件」的分组输出。
    ( cd "$root" && find . -mindepth 1 \( -type d -o -type f \) | LC_ALL=C sort ) | while IFS= read -r p; do
      local rel="${p#./}" m
      m=$(stat -c '%a' "$root/$rel")
      if [ -d "$root/$rel" ]; then
        echo "./$rel time=$ts mode=$m type=dir"
      else
        local sz h
        sz=$(stat -c '%s' "$root/$rel")
        h=$(sha256sum "$root/$rel" | cut -d' ' -f1)
        echo "./$rel time=$ts mode=$m size=$sz sha256digest=$h"
      fi
    done
  } > "$out"
}

# ── 打包：写 .PKGINFO/.BUILDINFO/.MTREE 再 tar+zstd ────────────────────
pack_pkg() {
  local pkgdir="$1" name="$2" arch="$3" desc="$4" outpkg="$5"; shift 5
  local deps=("$@")
  local dep

  cat > "$pkgdir/.PKGINFO" <<EOF
# Generated by build-arch.sh (makepkg-compatible)
pkgname = $name
pkgbase = $PKGBASE
xdata = pkgtype=split
pkgver = $PKGVER-$PKGREL
pkgdesc = $desc
url = https://github.com/cyrushmh/wordbuddy-github
builddate = $BUILDDATE
packager = $PACKAGER
size = $(du -sb "$pkgdir" | cut -f1)
arch = $arch
license = MIT
EOF
  for dep in "${deps[@]}"; do echo "depend = $dep" >> "$pkgdir/.PKGINFO"; done

  cat > "$pkgdir/.BUILDINFO" <<EOF
format = 2
pkgname = $name
pkgbase = $PKGBASE
pkgver = $PKGVER-$PKGREL
pkgarch = $arch
builddate = $BUILDDATE
builddir = /build
buildenv = !distcc
buildenv = color
buildenv = !ccache
buildenv = check
buildenv = !sign
options = strip
options = docs
options = !libtool
options = !staticlibs
options = emptydirs
options = zipman
options = purge
options = debug
EOF

  # makepkg 惯例：man page 以 gzip 压缩（对应 options=zipman）
  if [ -d "$pkgdir/usr/share/man" ]; then
    find "$pkgdir/usr/share/man" -type f ! -name '*.gz' -exec gzip -9 -n -f {} +
  fi

  # .MTREE 生成时不包含自身（与真实包一致：清单里只有 .PKGINFO/.BUILDINFO）
  gen_mtree "$pkgdir" "$WORK/mtree" "$BUILDDATE"
  cp "$WORK/mtree" "$pkgdir/.MTREE"

  ( cd "$pkgdir" && tar -cf - . ) | zstd -q -19 -T0 -o "$outpkg"
  echo "    -> $(basename "$outpkg")  ($(du -h "$outpkg" | cut -f1))"
}

rm -rf "$OUT"; mkdir -p "$OUT"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# ── 步骤 1：生成源码归档（makepkg 的 source=() 所指物） ──────────────────
log "打包源码归档 $PKGBASE-$PKGVER.tar.gz"
SRCDIR="$WORK/src"
mkdir -p "$SRCDIR/$PKGBASE-$PKGVER"
tar -C "$ROOT" -cf - \
      Makefile classics.1 classics.zh_CN.1 LICENSE data src \
    | tar -C "$SRCDIR/$PKGBASE-$PKGVER" -xf -
tar -C "$SRCDIR" -czf "$WORK/$PKGBASE-$PKGVER.tar.gz" "$PKGBASE-$PKGVER"

SUM=$(sha256sum "$WORK/$PKGBASE-$PKGVER.tar.gz" | cut -d' ' -f1)
log "归档 sha256 = $SUM"
if [ "${FILL_SUMS:-0}" = "1" ]; then
  sed -i "s/^sha256sums=(.*)$/sha256sums=('$SUM')/" "$ROOT/PKGBUILD"
  log "已回填 PKGBUILD 的 sha256sums"
fi

# ── 步骤 2：主包（架构相关）× 3 架构 ────────────────────────────────────
for ARCH in x86_64 aarch64 riscv64; do
  CC_FOR_ARCH="${CC_MAP[$ARCH]:-}"
  command -v "$CC_FOR_ARCH" >/dev/null 2>&1 || { echo "--- 跳过 $ARCH（缺 $CC_FOR_ARCH）"; continue; }
  log "构建 classics [$ARCH]（CC=$CC_FOR_ARCH）"

  B="$WORK/build-$ARCH"
  rm -rf "$B"; mkdir -p "$B/srcdir" "$B/pkgdir"
  tar -C "$B/srcdir" -xzf "$WORK/$PKGBASE-$PKGVER.tar.gz"

  # —— build() ——
  ( cd "$B/srcdir/$PKGBASE-$PKGVER" || exit 1
    make clean >/dev/null 2>&1 || true
    make CC="$CC_FOR_ARCH" DPKG_MK= )
  [ -x "$B/srcdir/$PKGBASE-$PKGVER/$PKGBASE" ] || die "$ARCH 构建失败：未产出二进制"

  # —— package_classics() ——
  PKGDIR="$B/pkgdir"
  S="$B/srcdir/$PKGBASE-$PKGVER"
  ( cd "$S" && make DESTDIR="$PKGDIR" install-bin )
  install -Dm644 "$S/classics.1"        "$PKGDIR/usr/share/man/man1/classics.1"
  install -Dm644 "$S/classics.zh_CN.1"  "$PKGDIR/usr/share/man/zh_CN/man1/classics.1"
  install -Dm644 "$S/LICENSE"           "$PKGDIR/usr/share/licenses/classics/LICENSE"

  pack_pkg "$PKGDIR" classics "$ARCH" \
    "经典典籍阅读与编码安全解码命令行工具（严格 UTF-8 优先，GB18030 回退）" \
    "$OUT/classics-$PKGVER-$PKGREL-$ARCH.pkg.tar.zst" \
    "glibc" "classics-data=$PKGVER-$PKGREL"
done

# ── 步骤 3：数据子包（arch=any，只打一份） ───────────────────────────────
log "构建 classics-data [any]（纯文本，不随架构重复打包）"
B="$WORK/build-data"
rm -rf "$B"; mkdir -p "$B/srcdir" "$B/pkgdir"
tar -C "$B/srcdir" -xzf "$WORK/$PKGBASE-$PKGVER.tar.gz"
S="$B/srcdir/$PKGBASE-$PKGVER"
( cd "$S" && make DESTDIR="$B/pkgdir" install-data )
install -Dm644 "$S/LICENSE" "$B/pkgdir/usr/share/licenses/classics-data/LICENSE"

pack_pkg "$B/pkgdir" classics-data "any" \
  "classics 的典籍文本数据（架构无关，安装到 /usr/share/classics/）" \
  "$OUT/classics-data-$PKGVER-$PKGREL-any.pkg.tar.zst"

# ── 步骤 4：.SRCINFO（AUR 元数据，对应 makepkg --printsrcinfo）───────────
log "生成 .SRCINFO（AUR 提交所需）"
cat > "$OUT/.SRCINFO" <<EOF
pkgbase = $PKGBASE
	pkgdesc = 经典典籍阅读与编码安全解码命令行工具（严格 UTF-8 优先，GB18030 回退，绝不假装解码成功）
	pkgver = $PKGVER
	pkgrel = $PKGREL
	url = https://github.com/cyrushmh/wordbuddy-github
	arch = x86_64
	arch = aarch64
	arch = riscv64
	license = MIT
	makedepends = gcc
	makedepends = make
	source = $PKGBASE-$PKGVER.tar.gz
	sha256sums = $SUM

pkgname = classics
	pkgdesc = 经典典籍阅读与编码安全解码命令行工具（严格 UTF-8 优先，GB18030 回退）
	arch = x86_64
	arch = aarch64
	arch = riscv64
	depends = glibc
	depends = classics-data=$PKGVER-$PKGREL

pkgname = classics-data
	pkgdesc = classics 的典籍文本数据（架构无关，安装到 /usr/share/classics/）
	arch = any
EOF
echo "    -> .SRCINFO"

log "完成。产物清单："
find "$OUT" -mindepth 1 -maxdepth 1 -printf '    %s %f\n' | sort
