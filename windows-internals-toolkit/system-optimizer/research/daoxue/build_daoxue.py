def kind_of(name: str) -> str:
    """按节名判文体类型（韵/咒/经/诰/赞/偈/文/愿/启请/供养/皈依/结）。"""
    if name.endswith("韵"):
        return "韵"
    if "皈依" in name:
        return "皈依"
    if name.endswith("咒"):
        return "咒"
    if name.endswith("经"):
        return "经"
    if name.endswith("诰"):
        return "诰"
    if name.endswith("赞"):
        return "赞"
    if name.endswith("偈") or name in ("吊挂", "吊褂", "早课吊褂"):
        return "偈"
    if "愿" in name:
        return "愿"
    if "忏悔" in name or name.endswith("文"):
        return "文"
    if "供养" in name:
        return "供养"
    if name in ("提纲", "小启请"):
        return "启请"
    if name in ("举天尊", "转天尊"):
        return "举赞"
    if name in ("祝谢", "结经偈"):
        return "结行"
    if name in ("回向",):
        return "回向"
    return "其他"


def parse_sections(text: str) -> list[dict]:
    """把功课经文本切成 [{name, body}]：以【标题】为界。"""
    marks = list(re.finditer(r"【([^】]{1,40})】", text))
    out = []
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(text)
        body = text[m.end():end]
        body = " ".join(body.split())
        out.append({"name": m.group(1).strip(), "body": body})
    return out


def first_sentence(body: str, limit: int = 34) -> str:
    """取正文首句（截到首个句号/换行，限长），作为「节旨」引用（不复制全文）。"""
    s = body.strip()
    m = re.match(r"[^。！？]{4,}?[。！？]", s)
    s = m.group(0) if m else s[:limit]
    s = " ".join(s.split())
    if len(s) > limit:
        s = s[:limit] + "…"
    return s


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    h.update(path.read_bytes())
    return h.hexdigest()


