def bridge_pools() -> dict:
    """目标系统的 id 池（构建期实测，用于校验桥接无悬空）。"""
    pdoc = json.loads((CONCEPTS_DIR / "plang_taxonomy.json").read_text(encoding="utf-8"))
    ndoc = json.loads((CONCEPTS_DIR / "netsys_taxonomy.json").read_text(encoding="utf-8"))
    ldoc = json.loads((DATA_DIR / "langs_docs.json").read_text(encoding="utf-8"))
    ddoc = json.loads((CONCEPTS_DIR / "datong_taxonomy.json").read_text(encoding="utf-8"))
    bdoc = json.loads((CONCEPTS_DIR / "baigong_taxonomy.json").read_text(encoding="utf-8"))
    qdoc = json.loads((CONCEPTS_DIR / "quantum_taxonomy.json").read_text(encoding="utf-8"))
    zdoc = json.loads((CONCEPTS_DIR / "zhuangzi_taxonomy.json").read_text(encoding="utf-8"))
    cdoc = json.loads((CONCEPTS_DIR / "comp_taxonomy.json").read_text(encoding="utf-8"))
    adoc = json.loads((CONCEPTS_DIR / "apilab_taxonomy.json").read_text(encoding="utf-8"))
    prdoc = json.loads((CONCEPTS_DIR / "protec_taxonomy.json").read_text(encoding="utf-8"))
    return {
        "pdoc": pdoc,
        "models": {m["model"] for m in pdoc.get("execution_models", [])},
        "archs": {a["arch"] for a in pdoc.get("target_archs", [])},
        "domains": {d["domain"] for d in pdoc.get("domains", [])},
        "mods": {m["id"] for m in ndoc.get("modules", [])},
        "layers": {l["layer"] for l in ndoc.get("layers", [])},
        "natures": {n["nature"] for n in ndoc.get("natures", [])},
        "ldoc": ldoc,
        "datong": {c["id"] for c in ddoc.get("concepts", [])} | {
            p["id"] for p in ddoc.get("principles", [])},
        "baigong": {c["id"] for c in bdoc.get("concepts", [])},
        "quantum": {c["id"] for c in qdoc.get("concepts", [])},
        "zhuangzi": {c["id"] for c in zdoc.get("concepts", [])},
        "comp": {c["id"] for c in cdoc.get("concepts", [])},
        "apilab": {c["id"] for c in adoc.get("concepts", [])},
        "protec": {c["id"] for c in prdoc.get("concepts", [])},
    }


def bridge_ok(pools: dict, system: str, target: str) -> bool:
    """校验单条桥接目标在目标系统中真实存在。"""
    pdoc = pools["pdoc"]
    t = target.split(":", 1)[1] if ":" in target else target
    if t == "*":  # 整轴引用（如 arch:*）：只要轴名合法即可
        return target.split(":", 1)[0] in {
            "model", "arch", "domain", "layer", "nature"}
    if system == "plang":
        if target.startswith("model:"):
            return t in pools["models"]
        if target.startswith("arch:"):
            return t in pools["archs"]
        if target.startswith("domain:"):
            return t in pools["domains"]
        if target == "probe":
            return bool(pdoc.get("probe_results"))
        return False
    if system == "netsys":
        if target.startswith("module:"):
            return t in pools["mods"]
        if target.startswith("layer:"):
            return t in pools["layers"]
        if target.startswith("nature:"):
            return t in pools["natures"]
        return False
    if system == "langref":
        return t in pools["ldoc"] or target == "needs_verify"
    if system == "datong":
        return t in pools["datong"]
    if system == "protec":
        return target.startswith("concept:") and t in pools.get("protec", set())
    if system in ("baigong", "quantum", "zhuangzi", "comp", "apilab"):
        return target in pools.get(system, set())
    return False


def validate_bridges(raw: list[tuple], pools: dict = None) -> list[dict]:
    """校验桥接目标真实存在（plang 轴值 / netsys 模块 / langref 字段），无悬空边。"""
    pools = pools or bridge_pools()
    out = []
    for pid, system, target, relation, how in raw:
        if not bridge_ok(pools, system, target):
            raise SystemExit(f"[daoxue] 桥接悬空：{pid} → {system}:{target} 不存在")
        out.append({"principle": pid, "system": system, "target": target,
                    "relation": relation, "how": how})
    return out


def validate_fangshu_bridges(raw: list[tuple], fmap: dict, pools: dict) -> list[dict]:
    """校验方术层桥接：条目 id 已登记 + 目标真实存在（无悬空边）。

    生成的边同时带 ``principle``（该条目归属的治理原则，与治理层同构）
    与 ``fangshu``（溯源到具体方术条目）。
    """
    out = []
    for fid, system, target, relation, how in raw:
        if fid not in fmap:
            raise SystemExit(f"[daoxue] 方术桥接引用未登记条目：{fid}")
        if not bridge_ok(pools, system, target):
            raise SystemExit(f"[daoxue] 方术桥接悬空：{fid} → {system}:{target} 不存在")
        out.append({"principle": fmap[fid]["principle"], "system": system,
                    "target": target, "relation": relation, "how": how,
                    "fangshu": fid})
    return out


def check(doc: dict) -> list[str]:
    errs = []
    if doc.get("_meta", {}).get("schema") != SCHEMA:
        errs.append("schema 不符")
    c = doc.get("center", {})
    chs = c.get("chapters", [])
    if len(chs) != 81:
        errs.append(f"道德经章数应 81，实际 {len(chs)}")
    if [x["no"] for x in chs] != list(range(1, 82)):
        errs.append("章号非 1..81 连续")
    for x in chs:
        if (x["no"] <= 37) != (x["part"] == "道经"):
            errs.append(f"第 {x['no']} 章篇属错误：{x['part']}")
    pids = {p["id"] for p in doc.get("principles", [])}
    for x in chs:
        if x["principle"] not in pids:
            errs.append(f"第 {x['no']} 章原则未登记：{x['principle']}")
    for role in ("pre", "post"):
        secs = doc.get(role, {}).get("sections", [])
        if not secs:
            errs.append(f"{role} 无节次")
        if [s["idx"] for s in secs] != list(range(1, len(secs) + 1)):
            errs.append(f"{role} 节次序号不连续")
    if len(doc.get("middle", [])) != 2:
        errs.append("中间二级应为 2 部（心经/论语）")
    for b in doc.get("bridges", []):
        if b["principle"] not in pids:
            errs.append(f"桥接引用未登记原则：{b['principle']}")
    # ---- 方术子层（tier=3）不变量
    fs = doc.get("fangshu", {})
    doms = fs.get("domains", [])
    if len(doms) != len(FANGSHU_DOMAINS):
        errs.append(f"方术层应为 {len(FANGSHU_DOMAINS)} 域，实际 {len(doms)}")
    fids: dict = {}
    for d in doms:
        if d.get("count") != len(d.get("items", [])):
            errs.append(f"方术域 {d.get('domain')} count 与 items 不符")
        for x in d.get("items", []):
            if x["id"] in fids:
                errs.append(f"方术条目 id 重复：{x['id']}")
            fids[x["id"]] = x
            if x.get("principle") not in pids:
                errs.append(f"方术条目 {x['id']} 归属原则未登记：{x.get('principle')}")
            for k in ("name", "gist", "detail", "engineering"):
                if not x.get(k):
                    errs.append(f"方术条目 {x['id']} 缺字段：{k}")
    for b in doc.get("bridges", []):
        if b.get("fangshu") and b["fangshu"] not in fids:
            errs.append(f"方术桥接引用未登记条目：{b['fangshu']}")
    cnt = doc.get("counts", {})
    real = {
        "center_chapters": len(chs),
        "pre_sections": len(doc.get("pre", {}).get("sections", [])),
        "post_sections": len(doc.get("post", {}).get("sections", [])),
        "middle_canons": len(doc.get("middle", [])),
        "middle_sections": sum(len(m["sections"]) for m in doc.get("middle", [])),
        "principle_count": len(doc.get("principles", [])),
        "bridge_count": len(doc.get("bridges", [])),
        "fangshu_domains": len(doms),
        "fangshu_items": len(fids),
        "fangshu_bridge_count": sum(1 for b in doc.get("bridges", []) if b.get("fangshu")),
        "fangshu_needs_verify": sum(1 for x in fids.values() if x.get("needs_verify")),
    }
    for k, v in real.items():
        if cnt.get(k) != v:
            errs.append(f"counts.{k} 漂移：{cnt.get(k)} != {v}")
    return errs


def main() -> int:
    ap = argparse.ArgumentParser(description="构建/校验「道枢」概念系统")
    ap.add_argument("--src-dir", default=str(DEFAULT_SRC),
                    help="源文本目录（默认 research/daoxue/sources）")
    ap.add_argument("--check", action="store_true", help="只校验已生成的 JSON")
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args()

    if args.check:
        if not Path(args.out).exists():
            print(f"[daoxue] 未找到 {args.out}", file=sys.stderr)
            return 1
        errs = check(json.loads(Path(args.out).read_text(encoding="utf-8")))
        if errs:
            for e in errs:
                print(f"[daoxue][FAIL] {e}", file=sys.stderr)
            return 1
        print(f"[daoxue] check OK：{args.out}")
        return 0

    doc = build(Path(args.src_dir))
    errs = check(doc)
    if errs:
        for e in errs:
            print(f"[daoxue][FAIL] {e}", file=sys.stderr)
        return 1
    Path(args.out).write_text(
        json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"[daoxue] 已写入 {args.out}")
    print(f"[daoxue] 道德经 {doc['counts']['center_chapters']} 章 / "
          f"早坛 {doc['counts']['pre_sections']} 节 / "
          f"晚坛 {doc['counts']['post_sections']} 节 / "
          f"二级 {doc['counts']['middle_canons']} 部 {doc['counts']['middle_sections']} 段 / "
          f"原则 {doc['counts']['principle_count']} 条 / "
          f"桥接 {doc['counts']['bridge_count']} 条")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
