"""分布式计算共享与入网能力优化任务（platform="any"）。

立项一句话：**网里那些闲着的核，能不能用起来而不引狼入室？**

先说清楚和 BOINC 的界限（这是本模块最重要的判断，不是细节）
-------------------------------------------------------------
BOINC 的模式是**项目方下发可执行程序**，你的机器下载并运行它。信任链是
"我信任这个项目方"。这条链一旦断——项目方被入侵、镜像被劫持、DNS 被污染——
你就是在自家机器上跑别人的二进制。

本层**砍掉这条链**：只跑**内置可验证算子**（白名单里三个，就在 `native/distcompute.py`
里写着），**绝不下载、绝不执行任何外部代码**。

代价是算不了真实的科学项目；收益是——**网里任何一台机器入网，都不会因此获得
在你机器上执行代码的能力**。这个交换值得：我们要的是"把闲着的核用起来"，
不是"再开一个远程执行通道"。

可验证性怎么保证
----------------
每个算子都满足：**结果可被独立复算，且校验比计算便宜**——这正是 BOINC
**冗余双投**（redundant computing）能成立的前提：

| 算子 | 校验方式 | 校验成本 |
|---|---|---|
| 哈希原像搜索 | 对找到的 nonce 做一次哈希 | O(1)，远便宜于搜索 |
| 分块矩阵乘法 | 抽一行一列重算 | O(n) 而非 O(n²) |
| 蒙特卡洛求 π（固定种子） | 同种子原样复算 | 同量级但可控 |

两份独立结果一致才接受，不一致就标**存疑并重投**——
**不信任任何单个节点的自述**，这是分布式计算的常识。

入网后的能力优化（第三件事）
----------------------------
参与组网不只是"捐算力"，也是"借能力"：
- **计算**：把可切分的活派给网里强的机器，本机只做汇总。
- **图形**：登记网内 GPU/NPU 型号（只登记，不跑负载），重活派给有卡的机器。
- **网络**：让渡策略要认**计量网络**（手机热点/按量计费）——不是安全考量，
  是**别让人替你交流量费**，所以降权但不禁止。

本设备的让渡策略（限核、仅充电时、仅空闲时）只出**策略报告**，
改系统设置由你自己执行——工具不替你改机器的电源与调度策略。
"""

