"""预警应急任务（platform="any"）。

立项来自一句最朴素的判断：**预警只有落在"离我多远"上才有意义**。
一条 300 公里外的红色预警和一条 3 公里外的黄色预警，后者才该让你现在就动。

所以本模块的第一件事不是"接预警源"，而是**先把位置与距离算清楚**，口径按你定的：

1. **首选 = 网络定位 + 基站定位**。室内、地铁、隧道、省电模式都可能没有导航信号，
   但网络与基站几乎总在——先保证"任何情况下都有一个可用的地理位置与距离"，
   不出现"定位不可用"就说不了话的空洞。
2. **有导航定位时，导航 + 首选基线共同综合**，而不是"有导航就丢掉基站"。
   按精度倒数平方加权，并给基线留 5% 最低话语权：导航主导但不独占，
   一次 GNSS 跳变不至于把位置甩到几公里外；基线始终参与校核。
3. **两源互相校核**：偏差超 2 km 标"存疑"，两套结果都摆出来，不替用户判定谁对。

第二件事才是预警本身：按 CAP 1.2 的常用字段登记事件，算出**距你多远、
是否在影响半径内、粗估多久到边界**。粗估只给量级，报告里写明"不是预报"。

红线（写死，任何情况下不越）
----------------------------
- **不自动报警、不拨号、不发短信**。SOS 只生成**文本**，通道由你自己选
  （可以贴到 meshchat 的全体广播在局域网里发，也可以自己打电话）。
- **不擅自联网抓预警源**。订阅开关默认**关闭**；开了也只拉你自己填的 URL，
  拉不到就报"未能获取"，**绝不编造预警内容**。
- **没有预警就是没有预警**，不把"没数据"包装成"安全"。
"""

