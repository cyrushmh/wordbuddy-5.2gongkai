"""DNS 解析健康度只读诊断测试（v0.6.15）。全只读，monkeypatch 喂假 resolv/查询。"""
import sys

import pytest

sys.path.insert(0, "src/python")
from sysweeper.native import dnshealth


def test_dnshealth_report_no_query_tuple():
    ok, msg = dnshealth.dnshealth_report(query=False)
    assert isinstance(ok, bool) and isinstance(msg, str) and msg
    assert "解析探测" in msg and "跳过" in msg


def test_dnshealth_report_default_is_safe():
    """默认不出网：不传 query 时等价于 query=False（零解析请求）。"""
    ok, msg = dnshealth.dnshealth_report()
    assert ok and "跳过" in msg and "解析探测" in msg


def test_dnshealth_capabilities_markers():
    ok, msg = dnshealth.capabilities_report()
    assert "能力自检" in msg and "resolv.conf" in msg


def test_resolv_conf_generated(monkeypatch):
    monkeypatch.setattr(dnshealth.common, "run",
                        lambda cmd, timeout=5: (0, "# Generated by systemd-resolved\n"
                                                "nameserver 127.0.0.53\n")
                        if "resolv.conf" in cmd else (1, ""))
    ok, (ns, generated, _raw) = dnshealth._resolv_conf()
    assert ok and generated and "127.0.0.53" in ns


def test_query_latency_ok(monkeypatch):
    monkeypatch.setattr(dnshealth.socket, "getaddrinfo",
                        lambda host, port: [(2, 3, 0, "", ("93.184.216.34", 0))])
    ok, msg = dnshealth._query_latency()
    assert ok and "解析成功" in msg


def test_query_latency_fail(monkeypatch):
    def boom(*a, **k):
        raise OSError("no dns")
    monkeypatch.setattr(dnshealth.socket, "getaddrinfo", boom)
    ok, msg = dnshealth._query_latency()
    assert ok is False and "解析失败" in msg
